"""Các interface DAO (tầng Data). Controller/Service chỉ phụ thuộc vào interface,
không phụ thuộc vào SQLite — đúng nguyên tắc «use» trong biểu đồ lớp thiết kế."""
from __future__ import annotations
from abc import ABC, abstractmethod
from typing import Optional
from chobay.model.customer import Customer
from chobay.model.product import Product, Category, Review
from chobay.model.cart import Cart
from chobay.model.order import Order, Payment
from chobay.model.delivery import Shipping, Hub, DeliveryVehicle, TrackingEvent
from chobay.model.enums import DeliveryMode, OrderStatus, ShippingStatus
from chobay.model.search_log import SearchLog
from chobay.model.staff import Staff


class CustomerDAO(ABC):
    @abstractmethod
    def get_cust(self, customer_id: int) -> Optional[Customer]: ...
    @abstractmethod
    def update_cust(self, customer: Customer) -> None: ...
    @abstractmethod
    def change_pass(self, customer: Customer, new_hash: str) -> None: ...
    @abstractmethod
    def find_by_username(self, username: str) -> Optional[Customer]: ...


class StaffDAO(ABC):
    @abstractmethod
    def get_by_username(self, username: str) -> Optional[Staff]: ...


class ProductDAO(ABC):
    @abstractmethod
    def get_item(self, product_id: int) -> Optional[Product]: ...
    @abstractmethod
    def find_all(self) -> list[Product]: ...
    @abstractmethod
    def find_by_category(self, category_id: int) -> list[Product]: ...
    @abstractmethod
    def categories(self) -> list[Category]: ...
    @abstractmethod
    def update_stock(self, product_id: int, delta: int) -> None: ...
    @abstractmethod
    def get_embedding(self, product_id: int) -> tuple[list[float], str]: ...
    @abstractmethod
    def get_reviews(self, product_id: int) -> list[Review]: ...


class CartDAO(ABC):
    @abstractmethod
    def get_cart(self, customer: Customer) -> Cart: ...
    @abstractmethod
    def add_item(self, cart: Cart, product: Product, qty: int) -> None: ...
    @abstractmethod
    def update_cart(self, cart: Cart) -> None: ...
    @abstractmethod
    def remove_item(self, cart: Cart, product_id: int) -> None: ...
    @abstractmethod
    def clear(self, cart: Cart) -> None: ...


class OrderDAO(ABC):
    @abstractmethod
    def create_order(self, order: Order) -> int: ...
    @abstractmethod
    def get_order(self, order_id: int) -> Optional[Order]: ...
    @abstractmethod
    def find_by_customer(self, customer_id: int) -> list[Order]: ...
    @abstractmethod
    def update_status(self, order_id: int, status: OrderStatus) -> None: ...
    @abstractmethod
    def save_payment(self, order_id: int, payment: Payment) -> None: ...
    @abstractmethod
    def mark_paid(self, order_id: int) -> None: ...


class ShippingDAO(ABC):
    @abstractmethod
    def create_shipping(self, shipping: Shipping) -> int: ...
    @abstractmethod
    def get_by_order(self, order_id: int) -> Optional[Shipping]: ...
    @abstractmethod
    def get_by_id(self, shipping_id: int) -> Optional[Shipping]: ...
    @abstractmethod
    def add_event(self, shipping_id: int, event: TrackingEvent) -> None: ...
    @abstractmethod
    def update_status(self, shipping_id: int, status: ShippingStatus, approved_by: str | None = None) -> None: ...
    @abstractmethod
    def find_by_status(self, statuses: list[ShippingStatus]) -> list[Shipping]: ...


class VehicleDAO(ABC):
    @abstractmethod
    def hubs(self) -> list[Hub]: ...
    @abstractmethod
    def find_available(self, mode: DeliveryMode) -> list[DeliveryVehicle]: ...
    @abstractmethod
    def mark_busy(self, vehicle_id: int) -> None: ...
    @abstractmethod
    def mark_idle(self, vehicle_id: int) -> None: ...
    @abstractmethod
    def find_all(self) -> list[DeliveryVehicle]: ...


class SearchLogDAO(ABC):
    @abstractmethod
    def save(self, log: SearchLog) -> int: ...
    @abstractmethod
    def find_recent(self, customer_id: int, limit: int = 5) -> list[SearchLog]: ...
